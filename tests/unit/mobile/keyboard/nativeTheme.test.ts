// Generated native theme: the keyboard's colours, Lexend fonts and icons are generated
// from the same sources as the app (src/ui/theme.css, @fontsource/lexend, bootstrap-icons), never hand-written. These
// drift tests fail when a committed output no longer matches its source.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

const ROOT = resolve(__dirname, '../../../..');
const MOBILE = join(ROOT, 'mobile');
const RES = join(MOBILE, 'android/app/src/main/res');
const SCRIPT = join(MOBILE, 'scripts/gen-native-theme.mjs');
const LEXEND = join(MOBILE, 'node_modules/@fontsource/lexend');
const ICONS = join(ROOT, 'node_modules/bootstrap-icons/icons');

const ICON_NAMES = [
  'keyboard', 'person-vcard', 'arrow-left-right', 'backspace', 'shift', 'shift-fill', 'capslock-fill', 'arrow-return-left',
  'chevron-down', 'box-arrow-up-right', 'check-lg', 'lock', 'eye-slash', 'exclamation-triangle', 'x-lg',
];

type Gen = { ICON_NAMES: readonly string[]; iconXml: (svg: string) => string };
type Woff = { woffToSfnt: (b: Buffer) => Buffer };
let gen: Gen;
let woff: Woff;
beforeAll(async () => {
  // Computed specifiers: the scripts are plain .mjs with no type declarations.
  gen = (await import(pathToFileURL(SCRIPT).href)) as Gen;
  woff = (await import(pathToFileURL(join(MOBILE, 'scripts/woff.mjs')).href)) as Woff;
});

const read = (p: string) => readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
const sha256 = (b: Buffer) => createHash('sha256').update(b).digest('hex');

/** --raf-color-* → #RRGGBB, parsed here independently of the generator. */
function themeColors(): { light: Map<string, string>; dark: Map<string, string> } {
  const css = read(join(ROOT, 'src/ui/theme.css')).replace(/\/\*[\s\S]*?\*\//g, '');
  const darkAt = css.indexOf('@media (prefers-color-scheme: dark)');
  expect(darkAt).toBeGreaterThan(0);
  const collect = (text: string) => {
    const out = new Map<string, string>();
    for (const m of text.matchAll(/--raf-color-([a-z0-9-]+)\s*:\s*(#[0-9a-fA-F]{6})\s*;/g)) {
      out.set(`raf_color_${m[1]!.replace(/-/g, '_')}`, m[2]!.toUpperCase());
    }
    return out;
  };
  // The dark block runs to the first line holding only "}" at column 0 after it.
  const darkEnd = css.indexOf('\n}', darkAt);
  return { light: collect(css.slice(0, darkAt)), dark: collect(css.slice(darkAt, darkEnd)) };
}

function colorsXml(path: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const m of read(path).matchAll(/<color name="([a-z0-9_]+)">(#[0-9A-F]{6})<\/color>/g)) out.set(m[1]!, m[2]!);
  return out;
}

describe('generated colours', () => {
  it('light raf_colors.xml equals the :root --raf-color-* of src/ui/theme.css', () => {
    const { light } = themeColors();
    expect(light.size).toBeGreaterThanOrEqual(16);
    expect(colorsXml(join(RES, 'values/raf_colors.xml'))).toEqual(light);
    for (const name of ['raf_color_bg', 'raf_color_surface', 'raf_color_text', 'raf_color_primary', 'raf_color_on_selected', 'raf_color_focus']) {
      expect(light.has(name)).toBe(true);
    }
  });

  it('night raf_colors.xml equals the prefers-color-scheme: dark block', () => {
    const { dark } = themeColors();
    expect(dark.size).toBeGreaterThanOrEqual(16);
    expect(colorsXml(join(RES, 'values-night/raf_colors.xml'))).toEqual(dark);
  });

  it('is headed as generated, sorted by name', () => {
    const text = read(join(RES, 'values/raf_colors.xml'));
    expect(text).toContain('<!-- Generated by mobile/scripts/gen-native-theme.mjs from src/ui/theme.css. Do not edit. -->');
    const names = [...colorsXml(join(RES, 'values/raf_colors.xml')).keys()];
    expect(names).toEqual([...names].sort());
  });
});

describe('generated icons', () => {
  it('holds exactly the 15 kb_ic_* drawables', () => {
    expect(gen.ICON_NAMES).toEqual(ICON_NAMES);
    const files = readdirSync(join(RES, 'drawable')).filter((f) => f.startsWith('kb_ic_')).sort();
    expect(files).toEqual(ICON_NAMES.map((n) => `kb_ic_${n.replace(/-/g, '_')}.xml`).sort());
  });

  it.each(ICON_NAMES)('kb_ic_%s equals the generator output for its SVG and keeps every path', (name) => {
    const svg = readFileSync(join(ICONS, `${name}.svg`), 'utf8');
    const xml = read(join(RES, `drawable/kb_ic_${name.replace(/-/g, '_')}.xml`));
    expect(xml).toBe(gen.iconXml(svg));
    const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
    const evenOdd = [...svg.matchAll(/<path[^>]*>/g)].filter((m) => m[0].includes('fill-rule="evenodd"')).length;
    expect([...xml.matchAll(/android:pathData="([^"]+)"/g)].map((m) => m[1])).toEqual(ds);
    expect((xml.match(/android:fillType="evenOdd"/g) ?? []).length).toBe(evenOdd);
    expect(xml).toContain('android:viewportWidth="16"');
    expect(xml).toContain('android:width="24dp"');
    expect(xml).toContain('<!-- bootstrap-icons (MIT), generated by mobile/scripts/gen-native-theme.mjs; tint set at runtime. -->');
  });

  it('refuses an SVG with any element other than svg and path', () => {
    const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16"><circle cx="8" cy="8" r="8"/></svg>';
    expect(() => gen.iconXml(svg)).toThrow();
  });
});

describe('generated fonts', () => {
  it.each([
    ['raf_lexend_regular.ttf', 'lexend-latin-400-normal.woff'],
    ['raf_lexend_semibold.ttf', 'lexend-latin-600-normal.woff'],
  ])('%s equals woffToSfnt of %s', (ttf, source) => {
    const out = readFileSync(join(RES, 'font', ttf));
    const expected = woff.woffToSfnt(readFileSync(join(LEXEND, 'files', source)));
    expect(sha256(out)).toBe(sha256(expected));
    expect(out.readUInt32BE(0)).toBe(0x00010000); // TrueType
  });

  it('raf_lexend.xml is a family of 400 and 600', () => {
    const xml = read(join(RES, 'font/raf_lexend.xml'));
    expect(xml).toContain('<font-family');
    expect(xml).toMatch(/android:fontWeight="400"[^>]*android:font="@font\/raf_lexend_regular"/);
    expect(xml).toMatch(/android:fontWeight="600"[^>]*android:font="@font\/raf_lexend_semibold"/);
    expect(xml).toMatch(/app:fontWeight="400"/);
    expect((xml.match(/fontStyle="normal"/g) ?? []).length).toBe(4);
  });

  it('the OFL licence is copied from the package', () => {
    expect(read(join(MOBILE, 'android/fonts-LICENSE-lexend.txt'))).toBe(read(join(LEXEND, 'LICENSE')));
  });
});

describe('gen-native-theme.mjs', () => {
  let tmp: string;
  beforeAll(() => {
    tmp = mkdtempSync(join(tmpdir(), 'raf-theme-'));
  });
  afterAll(() => rmSync(tmp, { recursive: true, force: true }));
  const run = (...args: string[]) => spawnSync(process.execPath, [SCRIPT, ...args], { cwd: MOBILE, encoding: 'utf8' });

  it('--check exits 0 on the committed outputs', () => {
    const r = run('--check');
    expect(r.stdout + r.stderr).not.toMatch(/differs|missing/);
    expect(r.status).toBe(0);
  });

  it('--check exits 1 and names an output that is missing or differs', () => {
    const missing = run('--check', '--out', tmp);
    expect(missing.status).toBe(1);
    expect(missing.stdout + missing.stderr).toContain('raf_colors.xml');
    expect(run('--out', tmp).status).toBe(0);
    expect(run('--check', '--out', tmp).status).toBe(0);
    const night = join(tmp, 'android/app/src/main/res/values-night/raf_colors.xml');
    expect(existsSync(night)).toBe(true);
    writeFileSync(night, read(night).replace('raf_color_bg">#', 'raf_color_bg">#0'));
    const drift = run('--check', '--out', tmp);
    expect(drift.status).toBe(1);
    expect(drift.stdout + drift.stderr).toContain('values-night');
  });

  it('runs before every web build', () => {
    const pkg = JSON.parse(readFileSync(join(MOBILE, 'package.json'), 'utf8')) as { scripts: { build: string } };
    expect(pkg.scripts.build.startsWith('node scripts/gen-native-theme.mjs --check && ')).toBe(true);
  });
});

const SINGULAR: Record<Language, Readonly<Record<string, string>>> = { zh: {}, en: enOne };

/** The singular forms of one language (read-only; tests check each has a plural key with the same words to fill). */
export function mobileSingulars(language: Language): Readonly<Record<string, string>> {
  return SINGULAR[language];
}

/** The mobile app's own words in one language (read-only; tests check both tables match). */
export function mobileMessages(language: Language): Readonly<Record<string, string>> {
  return MOBILE[language];
}

function interpolate(template: string, params?: MessageParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (params[name] === undefined ? whole : String(params[name])));
}

export function mt(language: Language, key: string, params?: MessageParams): string {
  const own = (params?.n === 1 ? SINGULAR[language][key] : undefined) ?? MOBILE[language][key];
  return own === undefined ? translate(language, key, params) : interpolate(own, params);
}

/** `t` for the mobile app: mobile words first, then the shared dictionary. Re-renders on language change. */
export function useMT(): (key: MobileKey | (string & {}), params?: MessageParams) => string {
  const language = useLanguage();
  return useCallback((key, params) => mt(language, key, params), [language]);
}

// Generates the native theme of the resume keyboard. Node stdlib only.
//   node scripts/gen-native-theme.mjs           write the outputs
//   node scripts/gen-native-theme.mjs --check   exit 1 and list every output that is missing or differs
//   --out <dir>                                 write or check under <dir> instead of mobile/ (tests)
// Sources: ../src/ui/theme.css (--raf-color-*, light and dark), @fontsource/lexend's latin 400 and 600 WOFF files in
// mobile/node_modules (converted to TTF, no download), and bootstrap-icons SVGs in the repository's node_modules (the
// package Icon.tsx imports). The outputs are committed; the web build runs --check so a stale resource stops it.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { woffToSfnt } from './woff.mjs';

const MOBILE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = resolve(MOBILE, '..');
const RES = 'android/app/src/main/res';

/** One meaning each. Output kb_ic_<name with _>.xml. */
export const ICON_NAMES = [
  'keyboard', 'person-vcard', 'arrow-left-right', 'backspace', 'shift', 'shift-fill', 'capslock-fill', 'arrow-return-left',
  'chevron-down', 'box-arrow-up-right', 'check-lg', 'lock', 'eye-slash', 'exclamation-triangle', 'x-lg',
];

const COLORS_HEADER = '<!-- Generated by mobile/scripts/gen-native-theme.mjs from src/ui/theme.css. Do not edit. -->';
const ICON_HEADER = '<!-- bootstrap-icons (MIT), generated by mobile/scripts/gen-native-theme.mjs; tint set at runtime. -->';

const escapeXml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Top-level rules of a CSS text (comments already removed): [{ prelude, body }]. */
function rules(css) {
  const out = [];
  let depth = 0;
  let start = 0;
  let open = -1;
  for (let i = 0; i < css.length; i += 1) {
    const c = css[i];
    if (c === '{') {
      if (depth === 0) open = i;
      depth += 1;
    } else if (c === '}') {
      depth -= 1;
      if (depth < 0) throw new Error('theme.css: unbalanced braces');
      if (depth === 0) {
        out.push({ prelude: css.slice(start, open).trim(), body: css.slice(open + 1, i) });
        start = i + 1;
      }
    } else if (c === ';' && depth === 0) {
      start = i + 1; // an at-statement such as @import
    }
  }
  if (depth !== 0) throw new Error('theme.css: unbalanced braces');
  return out;
}

function hex(value, name) {
  const m = /^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/.exec(value.trim());
  if (!m) throw new Error(`theme.css: ${name} is not a hex colour`);
  const h = m[1].length === 3 ? [...m[1]].map((c) => c + c).join('') : m[1];
  return `#${h.toUpperCase()}`;
}

function colorDecls(body, into) {
  for (const m of body.matchAll(/--raf-color-([a-z0-9-]+)\s*:\s*([^;]+);/g)) {
    const name = `raf_color_${m[1].replace(/-/g, '_')}`;
    into.set(name, hex(m[2], `--raf-color-${m[1]}`));
  }
}

/** { light, dark }: Map raf_color_x_y → #RRGGBB from :root and from @media (prefers-color-scheme: dark) :root. */
export function parseThemeColors(css) {
  const light = new Map();
  const dark = new Map();
  for (const rule of rules(css.replace(/\/\*[\s\S]*?\*\//g, ''))) {
    if (rule.prelude.startsWith('@media')) {
      if (!/prefers-color-scheme\s*:\s*dark/.test(rule.prelude)) continue;
      for (const inner of rules(rule.body)) if (/(^|,)\s*:root\s*(,|$)/.test(inner.prelude)) colorDecls(inner.body, dark);
    } else if (/(^|,)\s*:root\s*(,|$)/.test(rule.prelude)) {
      colorDecls(rule.body, light);
    }
  }
  if (light.size === 0 || dark.size === 0) throw new Error('theme.css: no --raf-color-* found');
  return { light, dark };
}

export function colorsXml(colors) {
  const names = [...colors.keys()].sort();
  const lines = names.map((n) => `    <color name="${n}">${colors.get(n)}</color>`);
  return `<?xml version="1.0" encoding="utf-8"?>\n${COLORS_HEADER}\n<resources>\n${lines.join('\n')}\n</resources>\n`;
}

function attrs(text) {
  const out = new Map();
  for (const m of text.matchAll(/([a-zA-Z_:][\w:.-]*)\s*=\s*"([^"]*)"/g)) out.set(m[1], m[2]);
  return out;
}

/** A bootstrap-icons SVG → an Android vector drawable. Throws on anything it does not understand, so no icon is
 *  silently dropped. */
export function iconXml(svg) {
  const paths = [];
  let sawSvg = false;
  for (const m of svg.matchAll(/<(\/?)([a-zA-Z][\w:-]*)([^>]*)>/g)) {
    const [, closing, tag, rest] = m;
    if (tag === 'svg') {
      if (!closing) {
        const a = attrs(rest);
        if (a.get('viewBox') !== '0 0 16 16') throw new Error('icon: viewBox must be 0 0 16 16');
        sawSvg = true;
      }
      continue;
    }
    if (tag !== 'path') throw new Error(`icon: unsupported element <${tag}>`);
    if (closing) continue;
    const a = attrs(rest);
    for (const key of a.keys()) if (key !== 'd' && key !== 'fill-rule') throw new Error(`icon: unsupported path attribute ${key}`);
    const d = a.get('d');
    if (!d) throw new Error('icon: path without d');
    const rule = a.get('fill-rule');
    if (rule !== undefined && rule !== 'evenodd' && rule !== 'nonzero') throw new Error('icon: unsupported fill-rule');
    paths.push({ d, evenOdd: rule === 'evenodd' });
  }
  if (!sawSvg || paths.length === 0) throw new Error('icon: no svg or no path');
  const body = paths
    .map((p) => `    <path android:fillColor="#FF000000"${p.evenOdd ? ' android:fillType="evenOdd"' : ''} android:pathData="${escapeXml(p.d)}" />`)
    .join('\n');
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    ICON_HEADER,
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    '    android:width="24dp"',
    '    android:height="24dp"',
    '    android:viewportWidth="16"',
    '    android:viewportHeight="16">',
    body,
    '</vector>',
    '',
  ].join('\n');
}

export function fontFamilyXml() {
  const font = (weight, file) =>
    `    <font\n        android:fontStyle="normal"\n        android:fontWeight="${weight}"\n        android:font="@font/${file}"\n` +
    `        app:fontStyle="normal"\n        app:fontWeight="${weight}"\n        app:font="@font/${file}" />`;
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Lexend (SIL OFL 1.1, mobile/android/fonts-LICENSE-lexend.txt), generated by mobile/scripts/gen-native-theme.mjs',
    '     from @fontsource/lexend. Do not edit. -->',
    '<font-family xmlns:android="http://schemas.android.com/apk/res/android"',
    '    xmlns:app="http://schemas.android.com/apk/res-auto">',
    font(400, 'raf_lexend_regular'),
    font(600, 'raf_lexend_semibold'),
    '</font-family>',
    '',
  ].join('\n');
}

/** Every output: [{ path relative to mobile/, content: string | Buffer }]. */
export function outputs() {
  const { light, dark } = parseThemeColors(readFileSync(join(ROOT, 'src/ui/theme.css'), 'utf8'));
  const lexend = join(MOBILE, 'node_modules/@fontsource/lexend');
  const list = [
    { path: `${RES}/values/raf_colors.xml`, content: colorsXml(light) },
    { path: `${RES}/values-night/raf_colors.xml`, content: colorsXml(dark) },
    { path: `${RES}/font/raf_lexend.xml`, content: fontFamilyXml() },
    { path: `${RES}/font/raf_lexend_regular.ttf`, content: woffToSfnt(readFileSync(join(lexend, 'files/lexend-latin-400-normal.woff'))) },
    { path: `${RES}/font/raf_lexend_semibold.ttf`, content: woffToSfnt(readFileSync(join(lexend, 'files/lexend-latin-600-normal.woff'))) },
    { path: 'android/fonts-LICENSE-lexend.txt', content: readFileSync(join(lexend, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n') },
  ];
  for (const name of ICON_NAMES) {
    const svg = readFileSync(join(ROOT, 'node_modules/bootstrap-icons/icons', `${name}.svg`), 'utf8');
    list.push({ path: `${RES}/drawable/kb_ic_${name.replace(/-/g, '_')}.xml`, content: iconXml(svg) });
  }
  return list;
}

/** Same bytes, ignoring CRLF in text outputs (a Windows checkout may convert them). */
function same(file, content) {
  if (!existsSync(file)) return false;
  const disk = readFileSync(file);
  if (Buffer.isBuffer(content)) return disk.equals(content);
  return disk.toString('utf8').replace(/\r\n/g, '\n') === content;
}

function main(argv) {
  const check = argv.includes('--check');
  const outAt = argv.indexOf('--out');
  const base = outAt >= 0 && argv[outAt + 1] ? resolve(argv[outAt + 1]) : MOBILE;
  const stale = [];
  for (const { path, content } of outputs()) {
    const file = join(base, path);
    if (check) {
      if (!same(file, content)) stale.push(`${existsSync(file) ? 'differs' : 'missing'}: ${relative(base, file).replace(/\\/g, '/')}`);
      continue;
    }
    mkdirSync(dirname(file), { recursive: true });
    if (!same(file, content)) writeFileSync(file, content);
  }
  if (stale.length > 0) {
    console.error(`gen-native-theme: ${stale.length} generated resource(s) out of date; run node scripts/gen-native-theme.mjs`);
    for (const line of stale) console.error(`  ${line}`);
    process.exit(1);
  }
}

const invoked = process.argv[1] ? resolve(process.argv[1]) : '';
const self = fileURLToPath(import.meta.url);
if (process.platform === 'win32' ? invoked.toLowerCase() === self.toLowerCase() : invoked === self) main(process.argv.slice(2));
